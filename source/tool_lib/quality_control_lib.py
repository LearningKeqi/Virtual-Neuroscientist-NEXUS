    def compute_brain_volume_size(
        original_t1w_path: str,
        brain_mask_path: str
    ) -> Dict[str, float]:
        """
        Compute brain volume size from a brain mask.

        Parameters
        ----------
        original_t1w_path : str
            Path to the original T1w NIfTI image. Used to validate that the mask
            matches the image space/shape.
        brain_mask_path : str
            Path to the brain mask NIfTI image.

        Returns
        -------
        Dict[str, float]
            A dictionary with one key:
            {'brain_volume_size': <volume_in_mm3>}
        """
        # Load images
        t1_img = nib.load(original_t1w_path)
        mask_img = nib.load(brain_mask_path)

        t1_data = t1_img.get_fdata()
        mask_data = mask_img.get_fdata()

        # Basic compatibility checks
        if t1_data.shape != mask_data.shape:
            raise ValueError(
                f"Shape mismatch: T1 shape {t1_data.shape} vs mask shape {mask_data.shape}"
            )

        # if not np.allclose(t1_img.affine, mask_img.affine, atol=1e-3):
        #     raise ValueError("Affine mismatch between T1 image and brain mask.")

        # Get voxel volume from mask header (mm^3)
        voxel_sizes = mask_img.header.get_zooms()[:3]
        voxel_volume_mm3 = float(np.prod(voxel_sizes))

        # Treat all nonzero voxels as brain
        brain_voxel_count = int(np.sum(mask_data > 0))

        brain_volume_size = brain_voxel_count * voxel_volume_mm3

        return {"brain_volume_size": float(brain_volume_size/1000.0)}


