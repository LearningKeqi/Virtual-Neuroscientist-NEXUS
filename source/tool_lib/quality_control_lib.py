        def _get_mask_slices(data, mask, view='axial', num_slices=16):
            """
            Select slices following fMRIPrep/niworkflows bbox-cuts approach:
            1) Use mask to define the valid range [smin, smax] in each direction
            - First filter by direction-specific threshold (axial 0.3 / sagittal 0.2 / coronal 0.1)
            - If too few slices are filtered, fall back to the range where mask>0
            2) Pick num_slices evenly spaced positions within [smin, smax], excluding both endpoints (avoid edges)
            Returns: list of (img_slice_2d, mask_slice_2d, slice_index, axis_name)
            """
            view = view.lower()
            if view not in ['axial', 'sagittal', 'coronal']:
                raise ValueError("view must be 'axial', 'sagittal', or 'coronal'")

            if data.shape != mask.shape:
                raise ValueError(f"data.shape={data.shape} does not match mask.shape={mask.shape}")

            # Convert mask to bool uniformly
            mask_bool = mask.astype(bool)

            # Direction mapping: axis and threshold ratio (consistent with niworkflows)
            if view == 'axial':
                axis = 2
                axis_name = 'Z'
                frac = 0.30
            elif view == 'sagittal':
                axis = 0
                axis_name = 'X'
                frac = 0.20
            else:  # coronal
                axis = 1
                axis_name = 'Y'
                frac = 0.10

            shape = mask_bool.shape
            slice_area = int(np.prod([shape[i] for i in range(3) if i != axis]))  # pixels per slice
            if slice_area <= 0:
                raise ValueError("Abnormal input dimensions, slice_area<=0")

            # Compute the mask voxel count c[idx] for each slice
            # Equivalent to: sum over the two non-axis dimensions
            sum_axes = tuple(i for i in range(3) if i != axis)
            c = mask_bool.sum(axis=sum_axes)  # shape: (shape[axis],)

            # Direction threshold: ceil(slice_area * frac)
            th = int(np.ceil(slice_area * frac))

            # Use c > th to find "valid brain region" slices first
            B = np.where(c > th)[0]
            # If too few valid slices (less than num_slices), fall back to c > 0 (any brain present)
            if B.size < num_slices:
                B = np.where(c > 0)[0]

            if B.size == 0:
                raise ValueError("No brain voxels found in mask along the specified axis (all zeros).")

            # Define [smin, smax] using min/max of B
            smin = int(B.min())
            smax = int(B.max())
            if smax <= smin:
                # Extreme case: only one slice
                chosen = np.array([smin], dtype=int)
            else:
                # Pick num_slices points within [smin, smax], excluding both endpoints -> avoid edges
                # Equivalent to linspace(smin, smax, num_slices+2)[1:-1]
                cut_coords = np.linspace(smin, smax, num_slices + 2, dtype=float)[1:-1]
                chosen = np.unique(np.clip(np.rint(cut_coords).astype(int), smin, smax))

                # If deduplication causes insufficient count (can happen with very small range / large num_slices), pad
                if chosen.size < min(num_slices, (smax - smin + 1)):
                    # Uniformly pad within [smin, smax] to approach num_slices as closely as possible
                    full = np.arange(smin, smax + 1, dtype=int)
                    if full.size <= num_slices:
                        chosen = full
                    else:
                        pos = np.linspace(0, full.size - 1, num_slices, dtype=int)
                        chosen = np.unique(full[pos])

            slices = []
            for idx in chosen.tolist():
                if view == 'axial':
                    img_slice = data[:, :, idx]
                    mask_slice = mask_bool[:, :, idx]
                elif view == 'sagittal':
                    img_slice = data[idx, :, :]
                    mask_slice = mask_bool[idx, :, :]
                else:  # coronal
                    img_slice = data[:, idx, :]
                    mask_slice = mask_bool[:, idx, :]

                slices.append((img_slice, mask_slice, int(idx), axis_name))

            return slices


        def _render_brain_seg_tile_rgb_exact(
            img2d,
            brain_msk2d,
            seg2d,
            label_text,
            draw_lr,
            vmin,
            vmax,
            brain_lw=1.5,
            tissue_csf_lw=1.0,
            gmwm_lw=1.0,
        ):
            """
            Render a single tile:
            - Background T1: img2d
            - Red: brain mask contour
            - Green: tissue (GM+WM) vs CSF boundary (the original blue/green annotation was inverted; this follows the actual colors)
            - Blue: GM vs WM boundary
            - Text: X/Y/Z=idx
            - L/R: optional
            Output RGB uint8 with size strictly equal to img2d.shape (no padding, only cropping to target is allowed).

            Default labels:
            0 = background
            1 = CSF
            2 = GM
            3 = WM

            """
            H, W = img2d.shape
            dpi = 100
            fig = plt.figure(figsize=(W / dpi, H / dpi), dpi=dpi)
            ax = plt.axes([0, 0, 1, 1])

            ax.imshow(
                img2d, cmap="gray", origin="lower",
                vmin=vmin, vmax=vmax,
                aspect="equal",
                interpolation="nearest",
            )

            # green: tissue (GM+WM) vs CSF boundary
            # tissue_map: CSF=0, tissue(GM/WM)=1
            tissue_map = np.zeros_like(seg2d, dtype=float)
            tissue_map[seg2d >= 2] = 1.0
            has_csf = np.any(seg2d == 1)
            has_tissue = np.any(seg2d >= 2)
            if has_csf and has_tissue:
                ax.contour(tissue_map.astype(float), levels=[0.5], colors="green", linewidths=tissue_csf_lw)

            # blue: GM vs WM boundary (between 2 and 3)
            has_gm = np.any(seg2d == 2)
            has_wm = np.any(seg2d == 3)
            if has_gm and has_wm:
                ax.contour(seg2d.astype(float), levels=[2.5], colors="blue", linewidths=gmwm_lw)

            # label
            ax.text(
                0.02, 0.98, label_text,
                transform=ax.transAxes, ha="left", va="top",
                color="yellow", fontsize=10,
                bbox=dict(facecolor="black", alpha=0.4, edgecolor="none", pad=1),
            )

            # red: brain mask contour
            if np.any(brain_msk2d):
                ax.contour(brain_msk2d.astype(float), levels=[0.5], colors="red", linewidths=brain_lw)


            if draw_lr:
                ax.text(
                    0.02, 0.02, "L",
                    transform=ax.transAxes, ha="left", va="bottom",
                    color="cyan", fontsize=10, fontweight="bold",
                    bbox=dict(facecolor="black", alpha=0.35, edgecolor="none", pad=1),
                )
                ax.text(
                    0.98, 0.02, "R",
                    transform=ax.transAxes, ha="right", va="bottom",
                    color="cyan", fontsize=10, fontweight="bold",
                    bbox=dict(facecolor="black", alpha=0.35, edgecolor="none", pad=1),
                )

            ax.set_axis_off()
            fig.canvas.draw()

            # --- Get RGB (compatible) ---
            if hasattr(fig.canvas, "buffer_rgba"):
                rgba = np.asarray(fig.canvas.buffer_rgba())
                rgb = rgba[..., :3].copy()
            else:
                buf = np.frombuffer(fig.canvas.tostring_argb(), dtype=np.uint8)
                wpx, hpx = fig.canvas.get_width_height()
                argb = buf.reshape((hpx, wpx, 4))
                rgba = argb[..., [1, 2, 3, 0]]
                rgb = rgba[..., :3].copy()

            plt.close(fig)

            # --- Only allow cropping to target, no padding ---
            h2, w2 = rgb.shape[:2]
            if (h2, w2) != (H, W):
                if h2 < H or w2 < W:
                    raise RuntimeError(f"Rendered size smaller than target and padding is forbidden: got {(h2, w2)}, need {(H, W)}")
                y0 = (h2 - H) // 2
                x0 = (w2 - W) // 2
                rgb = rgb[y0:y0 + H, x0:x0 + W, :]

            return rgb



        def _need_flip_lr(affine):
            """Whether horizontal flipping is needed so display has L on the left, R on the right (neurological)."""
            xcode = nib.aff2axcodes(affine)[0]  # usually 'R' or 'L'
            return (xcode == 'L')


        def _scale_to_width_nn(arr2d, target_w):
            """Nearest-neighbor proportional scaling to fixed width target_w (no scipy/skimage dependency)."""
            h, w = arr2d.shape
            if w == target_w:
                return arr2d
            scale = target_w / float(w)
            target_h = max(1, int(np.rint(h * scale)))

            ys = np.linspace(0, h - 1, target_h)
            xs = np.linspace(0, w - 1, target_w)
            yi = np.clip(np.rint(ys).astype(int), 0, h - 1)
            xi = np.clip(np.rint(xs).astype(int), 0, w - 1)
            return arr2d[yi[:, None], xi[None, :]]


        def generate_brain_mask_and_tissue_seg_qc_montage_3x3(
            t1_path,
            brain_mask_path,
            seg_path,
            out_dir,
            vmax_percentile=99,
            brain_linewidth=1.5,
            gmwm_linewidth=1.0,
            tissue_csf_linewidth=1.0,
            save_name=None
        ):
            """
            Output 3x3 montage:
            - Rows: axial / sagittal / coronal
            - Columns: 3 slices per row
            - All tile widths are unified to the axial width X (other views are proportionally scaled to X)
            - No padding, no background fill; concatenate using np.concatenate
            - axial & coronal ensure L on the left, R on the right (fliplr if needed)
            """
            os.makedirs(out_dir, exist_ok=True)

            t1_nii = nib.load(t1_path)
            bm_nii = nib.load(brain_mask_path)
            seg_nii = nib.load(seg_path)

            t1 = t1_nii.get_fdata()
            brain_mask = bm_nii.get_fdata() > 0.5
            seg = seg_nii.get_fdata()

            if t1.shape != brain_mask.shape or t1.shape != seg.shape:
                raise ValueError(f"shape mismatch: T1 {t1.shape}, brain_mask {brain_mask.shape}, seg {seg.shape}")

            vmin = float(np.min(t1))
            vmax = float(np.percentile(t1, vmax_percentile))

            flip_lr = _need_flip_lr(t1_nii.affine)

            views = ["axial", "sagittal", "coronal"]
            per_view = 3

            # First take axial: determine unified width X (note that we use .T when displaying)
            axial_slices = _get_mask_slices(t1, brain_mask, view="axial", num_slices=per_view)
            while len(axial_slices) < per_view:
                axial_slices.append(axial_slices[-1])

            X = axial_slices[0][0].T.shape[1]

            row_imgs = []
            for v in views:
                slices = axial_slices if v == "axial" else _get_mask_slices(t1, brain_mask, view=v, num_slices=per_view)
                while len(slices) < per_view:
                    slices.append(slices[-1])

                tiles = []
                for (img_slice, bm_slice, idx, axis_name) in slices[:per_view]:
                    # Corresponding seg slice (aligned with view)
                    if v == "axial":
                        seg_slice = seg[:, :, idx]
                    elif v == "sagittal":
                        seg_slice = seg[idx, :, :]
                    else:  # coronal
                        seg_slice = seg[:, idx, :]

                    # Display space: uniformly use .T
                    img2d = img_slice.T
                    bm2d = (bm_slice > 0).T.astype(np.uint8)
                    seg2d = seg_slice.T

                    # L/R: flip axial & coronal if needed, and flip seg/brainmask synchronously
                    if v in ("axial", "coronal") and flip_lr:
                        img2d = np.fliplr(img2d)
                        bm2d = np.fliplr(bm2d)
                        seg2d = np.fliplr(seg2d)

                    # Proportional scaling to unified width X (no padding)
                    img2d = _scale_to_width_nn(img2d, X)
                    bm2d = _scale_to_width_nn(bm2d, X)
                    seg2d = _scale_to_width_nn(seg2d, X)

                    label = f"{axis_name}={int(idx)}"
                    draw_lr = (v in ("axial", "coronal"))

                    rgb = _render_brain_seg_tile_rgb_exact(
                        img2d=img2d,
                        brain_msk2d=bm2d,
                        seg2d=seg2d,
                        label_text=label,
                        draw_lr=draw_lr,
                        vmin=vmin,
                        vmax=vmax,
                        brain_lw=brain_linewidth,
                        tissue_csf_lw=tissue_csf_linewidth,
                        gmwm_lw=gmwm_linewidth,
                    )
                    tiles.append(rgb)

                # The 3 tiles per view should have the same height (same shape + same scaling)
                hs = [t.shape[0] for t in tiles]
                if len(set(hs)) != 1:
                    raise RuntimeError(f"{v} row tile heights inconsistent: {hs}. This should generally not happen.")

                row = np.concatenate(tiles, axis=1)  # horizontal concatenation without background
                row_imgs.append(row)

            # All three rows should have the same width (= 3*X)
            ws = [r.shape[1] for r in row_imgs]
            if len(set(ws)) != 1:
                raise RuntimeError(f"Row widths inconsistent: {ws}. This should not happen (all tile widths should be X).")

            montage = np.concatenate(row_imgs, axis=0)  # vertical concatenation without background

            out_path = os.path.join(out_dir, f"{save_name}_QC_T1w_TissueSeg.png")
            plt.imsave(out_path, montage)
            return out_path


        out = os.path.dirname(tissue_seg_path)
        save_name = get_nii_basename(tissue_seg_path)

