def read_mriqc_metric(subject_label: str, modality: str, metric_keys: Optional[list[str]] = None, output_dir: str = None) -> str:
    """
    Read MRIQC IQM metrics for a specified subject and modality, optionally filtering by metric keys.

    **Parameters:**
    - subject_label (str): Subject ID with or without the 'sub-' prefix (e.g., '0027003' or 'sub-0027003').
    - modality (str): Target modality, one of 'T1w' or 'bold'.
    - metric_keys (list[str] | None): Specific IQM keys to return; if None, return all available IQMs.
        - For T1w: valid metric keys include: ['cjv',	'cnr',	'efc',	'fber',	'fwhm_avg',	'fwhm_x',	'fwhm_y',	'fwhm_z',	'icvs_csf',	'icvs_gm',	'icvs_wm',	'inu_med',	'inu_range',	'qi_1',	'qi_2',	'rpve_csf',	'rpve_gm',	'rpve_wm',	'size_x',	'size_y',	'size_z',	'snr_csf',	'snr_gm',	'snr_total',	'snr_wm',	'snrd_csf',	'snrd_gm',	'snrd_total',	'snrd_wm',	'spacing_x',	'spacing_y',	'spacing_z',	'summary_bg_k',	'summary_bg_mad',	'summary_bg_mean',	'summary_bg_median',	'summary_bg_n',	'summary_bg_p05',	'summary_bg_p95',	'summary_bg_stdv',	'summary_csf_k',	'summary_csf_mad',	'summary_csf_mean',	'summary_csf_median',	'summary_csf_n',	'summary_csf_p05',	'summary_csf_p95',	'summary_csf_stdv',	'summary_gm_k',	'summary_gm_mad',	'summary_gm_mean',	'summary_gm_median',	'summary_gm_n',	'summary_gm_p05',	'summary_gm_p95',	'summary_gm_stdv',	'summary_wm_k',	'summary_wm_mad',	'summary_wm_mean',	'summary_wm_median',	'summary_wm_n',	'summary_wm_p05',	'summary_wm_p95',	'summary_wm_stdv',	'tpm_overlap_csf',	'tpm_overlap_gm',	'tpm_overlap_wm',	'wm2max'].
        - For bold: valid metric keys include: ['aor',	'aqi',	'dummy_trs',	'dvars_nstd',	'dvars_std',	'dvars_vstd',	'efc',	'fber',	'fd_mean',	'fd_num',	'fd_perc',	'fwhm_avg',	'fwhm_x',	'fwhm_y',	'fwhm_z',	'gcor',	'gsr_x',	'gsr_y',	'size_t',	'size_x',	'size_y',	'size_z',	'snr',	'spacing_tr',	'spacing_x',	'spacing_y',	'spacing_z',	'summary_bg_k',	'summary_bg_mad',	'summary_bg_mean',	'summary_bg_median',	'summary_bg_n',	'summary_bg_p05',	'summary_bg_p95',	'summary_bg_stdv',	'summary_fg_k',	'summary_fg_mad',	'summary_fg_mean',	'summary_fg_median',	'summary_fg_n',	'summary_fg_p05',	'summary_fg_p95',	'summary_fg_stdv',	'tsnr'].
    - output_dir (str): Absolute path to the MRIQC output root directory.

    **Outputs:**
     - dict: On success, returns a dict with:
        - subject (str): normalized subject label with 'sub-' prefix
        - modality (str): 'T1w' or 'bold'
        - metrics (dict): IQM key-value pairs (all IQMs if metric_keys is None; otherwise only requested keys, missing keys -> None)
    - str: On failure, returns an error message string (e.g., subject dir not found, unsupported modality, no JSON, or JSON load failure).

    """

    subject = subject_label if subject_label.startswith('sub-') else f"sub-{subject_label}"
    modality_lc = modality.lower() if modality else ""

    def emit(metrics: dict) -> str:
        mod_out = "T1w" if modality_lc == "t1w" else ("bold" if modality_lc == "bold" else modality)
        # return json.dumps({
        #     "subject": subject,
        #     "modality": mod_out,
        #     "metrics": metrics
        # }, ensure_ascii=False)

        return {
            "subject": subject,
            "modality": mod_out,
            "metrics": metrics
        }

    subject_root = os.path.join(output_dir, subject)
    if not os.path.isdir(subject_root):
        candidates = sorted(glob.glob(os.path.join(output_dir, f"{subject}*")))
        if candidates:
            subject_root = candidates[0]

    if not os.path.isdir(subject_root):
        return f"Subject directory not found under output_dir: {output_dir}"

    if modality_lc not in {"t1w", "bold"}:
        return f"Modality not supported: {modality_lc}"

    patterns = [
        os.path.join(subject_root, "**", "anat", "*T1w.json")
    ] if modality_lc == "t1w" else [
        os.path.join(subject_root, "**", "func", "*_bold.json")
    ]

    matches: list[str] = []
    for p in patterns:
        matches.extend(glob.glob(p, recursive=True))

    if not matches:
        return "No IQM JSON files found for this subject."

    json_path = sorted(matches)[0]
    try:
        with open(json_path, 'r') as f:
            data = json.load(f)
    except Exception:
        return f"Failed to load IQM JSON file: {json_path}"

    iqm_all = {k: v for k, v in data.items() if k not in {"bids_meta", "provenance"}}
    if metric_keys:
        iqm_filtered = {k: iqm_all[k] if k in iqm_all else None for k in metric_keys}
        return emit(iqm_filtered)

    return emit(iqm_all)




