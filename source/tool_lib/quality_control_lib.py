    import numpy as np
    import nibabel as nib
    from nibabel.processing import resample_from_to


    def eval_normalize_nmi_and_dice(
        mean_fmri_normalized_to_mni: str,
        mean_fmri_normalized_to_mni_brain_mask: str,
        mni_brain_image: str,
        mni_brain_mask: str,
        bins: int = 64,
    ) -> dict:
        """
        Returns two metrics (as a dict):
        - nmi: Studholme NMI = (H(X)+H(Y)) / H(X,Y)
        - mask_overlap_dice: Dice(mean_fmri_mask, t1w_mask)

        If needed, resample mean_fmri and its mask to the grid of mni_brain_image:
        - Image: linear interpolation
        - Mask: nearest neighbor

        NMI is computed within the intersection of both masks, with robust normalization to [0,1] and a
        fixed histogram range for more stable comparability.
        """

        def load_img(path: str) -> nib.Nifti1Image:
            return nib.load(path)

        def resample_to_ref(src: nib.Nifti1Image, ref: nib.Nifti1Image, is_mask: bool) -> nib.Nifti1Image:
            same_shape = (src.shape == ref.shape)
            same_aff = np.allclose(src.affine, ref.affine, rtol=1e-4, atol=1e-3)
            if same_shape and same_aff:
                return src
            return resample_from_to(src, ref, order=0 if is_mask else 1)

        def robust_scale_01(vec: np.ndarray, p_low: float = 1.0, p_high: float = 99.0) -> np.ndarray:
            if vec.size == 0:
                return vec.astype(np.float32)

            lo = np.percentile(vec, p_low)
            hi = np.percentile(vec, p_high)

            if (not np.isfinite(lo)) or (not np.isfinite(hi)) or (hi <= lo):
                lo = float(np.min(vec))
                hi = float(np.max(vec))

            if (not np.isfinite(lo)) or (not np.isfinite(hi)) or (hi <= lo):
                return np.zeros_like(vec, dtype=np.float32)

            v = np.clip(vec, lo, hi)
            v = (v - lo) / (hi - lo)
            return v.astype(np.float32)

        def entropy(p: np.ndarray) -> float:
            p = p[p > 0]
            return float(-np.sum(p * np.log(p))) if p.size else 0.0

        # --- load reference (T1) ---
        t1_img = load_img(mni_brain_image)
        t1 = t1_img.get_fdata().astype(np.float32)

        t1_mask_img = resample_to_ref(load_img(mni_brain_mask), t1_img, is_mask=True)
        t1_mask = (t1_mask_img.get_fdata() > 0.5)

        # --- load fmri + resample to T1 grid if needed ---
        fmri_img = resample_to_ref(load_img(mean_fmri_normalized_to_mni), t1_img, is_mask=False)
        fmri = fmri_img.get_fdata().astype(np.float32)

        fmri_mask_img = resample_to_ref(load_img(mean_fmri_normalized_to_mni_brain_mask), t1_img, is_mask=True)
        fmri_mask = (fmri_mask_img.get_fdata() > 0.5)

        # --- Dice overlap ---
        inter = np.logical_and(fmri_mask, t1_mask).sum()
        denom = fmri_mask.sum() + t1_mask.sum()
        dice = float((2.0 * inter) / denom) if denom > 0 else float("nan")

        # --- NMI on intersection mask ---
        valid = np.logical_and(fmri_mask, t1_mask)
        valid &= np.isfinite(fmri) & np.isfinite(t1)

        if not np.any(valid):
            raise ValueError("Empty intersection mask (or all invalid). Please check that both masks are in the same space and overlap.")

        fmri_vec = fmri[valid].ravel()
        t1_vec = t1[valid].ravel()

        fmri_n = robust_scale_01(fmri_vec, 1.0, 99.0)
        t1_n = robust_scale_01(t1_vec, 1.0, 99.0)

        hist2d, _, _ = np.histogram2d(
            fmri_n, t1_n,
            bins=bins,
            range=[[0.0, 1.0], [0.0, 1.0]]
        )

        s = float(hist2d.sum())
        if s <= 0:
            nmi = float("nan")
        else:
            pxy = hist2d / s
            px = np.sum(pxy, axis=1)
            py = np.sum(pxy, axis=0)
            Hx = entropy(px)
            Hy = entropy(py)
            Hxy = entropy(pxy)
            nmi = float((Hx + Hy) / Hxy) if Hxy > 0 else float("nan")

        return {"NMI_fmri2mni": nmi, "Dice_fmri2mni": dice}


