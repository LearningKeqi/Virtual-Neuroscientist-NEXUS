    def compute_nmi_ncc(t1_path, mni_path, mni_brain_mask, bins=64):
        """
        Compute (more suitable for cross-subject comparison) between T1w (MNI space) and the MNI template:
        - Normalized Mutual Information (NMI) (Studholme common definition: (H(X)+H(Y))/H(X,Y))
        - Normalized Cross-Correlation (NCC) (here, Pearson correlation coefficient)

        Inputs are consistent with the previous version:
        t1_path, mni_path, mni_brain_mask, bins=64

        Key strategies (improving cross-subject comparability):
        1) Robust normalization of t1/mni within the same mask: clip by [p1, p99] percentiles and linearly map to [0,1]
        2) Fix the NMI histogram range=[[0,1],[0,1]] so that bin meanings are consistent across subjects
        3) Use mni_brain_mask and additionally exclude t1==0 background voxels and NaN/Inf

        Returns:
        nmi (float), ncc (float)
        """

        def load_nifti(path):
            img = nib.load(path)
            data = img.get_fdata().astype(np.float32)
            return img, data, img.affine

        def robust_minmax_scale_to_01(vec, p_low=1.0, p_high=99.0):
            """
            vec: 1D array (voxels after masking)
            Returns: vec normalized to [0,1], and the (lo, hi) used for normalization
            """
            if vec.size == 0:
                return vec.astype(np.float32), (np.nan, np.nan)

            lo = np.percentile(vec, p_low)
            hi = np.percentile(vec, p_high)

            # Extreme case protection: if percentiles are equal (nearly constant/strongly discrete), fall back to min/max
            if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
                lo = float(np.min(vec))
                hi = float(np.max(vec))

            if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
                # Still failing: treat as constant
                return np.zeros_like(vec, dtype=np.float32), (lo, hi)

            v = np.clip(vec, lo, hi)
            v = (v - lo) / (hi - lo)
            return v.astype(np.float32), (float(lo), float(hi))

        def entropy_from_prob(p):
            """p: probability array (can be multi-dimensional); returns Shannon entropy (natural log)."""
            p = p[p > 0]
            if p.size == 0:
                return 0.0
            return float(-np.sum(p * np.log(p)))

        # --- load ---
        t1_img, t1, _ = load_nifti(t1_path)
        mni_img, mni, _ = load_nifti(mni_path)

        if isinstance(mni_brain_mask, str):
            mask_img, mask_data, _ = load_nifti(mni_brain_mask)
        else:
            mask_data = np.asarray(mni_brain_mask)

        from nibabel.processing import resample_from_to

        # --- resample T1 to MNI grid when needed ---
