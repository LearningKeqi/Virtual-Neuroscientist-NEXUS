def fmri_coregister_to_anat_qc(
    mean_fmri_registered_to_t1w: str,
    mean_fmri_brain_mask_registered_to_t1w: str,
    t1w_brain_image: str,
    t1w_brain_mask: str,
    t1w_brain_seg: str,
    metric_or_visual: str,
):
    """
    Perform quality control on the fmri to anat co-registration step.
    You can choose to get Normalized Mutual Information (NMI)  and Dice Similarity of brain mask between co-registered fmri and t1w, or visually check the result.

    **Parameters:**
    - mean_fmri_registered_to_t1w: (str). Absolute path to the mean fMRI image coregistered to t1w.
    - mean_fmri_brain_mask_registered_to_t1w: (str). Absolute path to the brain mask of the mean fMRI image coregistered to t1w.
    - t1w_brain_image: (str). Absolute path to the original t1w image (with skull).
    - t1w_brain_mask: (str). Absolute path to the t1w brain mask.
    - t1w_brain_seg: (str). Absolute path to the t1w brain segment, hard brain tissue segmentation map in which each voxel is assigned a discrete label corresponding to CSF, gray matter, or white matter, used for QC..
    - metric_or_visual: (str). Choice of metric or visual QC. 'metric' or 'visual'.

    **Outputs:**
    - If metric_or_visual is 'metric', return a dictionary containing the Normalized Mutual Information (NMI)  and Dice Similarity of brain mask between co-registered fmri and t1w, {'NMI_fmri2t1w': nmi_value, 'Dice_fmri2t1w': dice_value}.
    - If metric_or_visual is 'visual', return the visual evaluation result of the fmri to anat co-registration.
    """

    # visual inspection: overlay
    # metric: MI    

    import os
    import numpy as np
    import nibabel as nib
    import matplotlib.pyplot as plt
    from matplotlib.gridspec import GridSpec


    def construct_fmri_coreg_t1w_qc_image(
        mean_fmri_registered_to_t1w,
        t1w_brain_mask,
        t1w_brain_seg
        ):

        def _need_flip_lr(affine):
            """
            Whether horizontal flipping is needed to ensure L is on the left and R is on the right
            (neurological display). If the x-axis code of the affine is 'L', a horizontal flip is required.
            """
            xcode = nib.aff2axcodes(affine)[0]
            return (xcode == 'L')


        def _scale_to_width_nn(arr2d, target_w):
            """Nearest-neighbor proportional scaling to fixed width target_w (no scipy/skimage dependency)."""
            h, w = arr2d.shape
            if w == target_w:
                return arr2d
            scale = target_w / float(w)
            target_h = max(1, int(np.rint(h * scale)))

            ys = np.linspace(0, h - 1, target_h)
            xs = np.linspace(0, w - 1, target_w)
            yi = np.clip(np.rint(ys).astype(int), 0, h - 1)
            xi = np.clip(np.rint(xs).astype(int), 0, w - 1)
            return arr2d[yi[:, None], xi[None, :]]


        def _get_mask_indices(mask3d, view='axial', num_slices=3):
            """
            Use mask (bool) to select slice indices following the niworkflows bbox-cuts approach.
            Returns: list of (idx, axis_name)
            """
            view = view.lower()
            if view not in ['axial', 'sagittal', 'coronal']:
                raise ValueError("view must be 'axial', 'sagittal', or 'coronal'")

            mask_bool = mask3d.astype(bool)
            shape = mask_bool.shape

            if view == 'axial':
                axis = 2
                axis_name = 'Z'
                frac = 0.30
            elif view == 'sagittal':
                axis = 0
                axis_name = 'X'
                frac = 0.20
            else:
                axis = 1
                axis_name = 'Y'
                frac = 0.10

            slice_area = int(np.prod([shape[i] for i in range(3) if i != axis]))
            if slice_area <= 0:
                raise ValueError("Abnormal input dimensions, slice_area<=0")

            sum_axes = tuple(i for i in range(3) if i != axis)
            c = mask_bool.sum(axis=sum_axes)

            th = int(np.ceil(slice_area * frac))
            B = np.where(c > th)[0]
            if B.size < num_slices:
                B = np.where(c > 0)[0]

            if B.size == 0:
                raise ValueError("Empty mask; cannot select slices.")

            smin = int(B.min())
            smax = int(B.max())

            if smax <= smin:
                chosen = [smin]
            else:
                cut_coords = np.linspace(smin, smax, num_slices + 2, dtype=float)[1:-1]
                chosen = np.unique(np.clip(np.rint(cut_coords).astype(int), smin, smax)).tolist()

            while len(chosen) < num_slices:
                chosen.append(chosen[-1])

            return [(int(idx), axis_name) for idx in chosen[:num_slices]]


        def _render_fmri_coreg_tile_rgb_exact(
            fmri2d,
            brainmask2d,
            seg2d,
            label_text,
            draw_lr,
            vmin,
            vmax,
            brainmask_lw=1.5,
            gmwm_lw=1.2,
            dpi=150,
            font_frac=0.08,
            lr_font_frac=0.08,
            contour_color_mask="red",
            contour_color_gmwm="red",   # change to "blue" if you want to distinguish
        ):
            """
            Tile rendering:
            - Background: mean fMRI grayscale
            - Contour: T1 brain mask + GM/WM boundary
            - Annotations: X/Y/Z=idx + optional L/R
            Output RGB uint8 with size strictly equal to fmri2d.shape (only cropping is allowed, no padding).
            """
            H, W = fmri2d.shape

            # Font scales with tile size (avoid text being too big / brain too small)
            base = min(H, W)
            label_px = max(8, int(base * font_frac))
            lr_px = max(10, int(base * lr_font_frac))
            label_pt = label_px * 72.0 / dpi
            lr_pt = lr_px * 72.0 / dpi

            fig = plt.figure(figsize=(W / dpi, H / dpi), dpi=dpi)
            ax = plt.axes([0, 0, 1, 1])

            ax.imshow(
                fmri2d,
                cmap="gray",
                origin="lower",
                vmin=vmin,
                vmax=vmax,
                aspect="equal",
                interpolation="nearest",
                zorder=1,
            )

            # brain mask contour
            if np.any(brainmask2d):
                ax.contour(
                    brainmask2d.astype(float),
                    levels=[0.5],
                    colors=contour_color_mask,
                    linewidths=brainmask_lw,
                    zorder=4,
                )

            # GM/WM boundary (2 vs 3 -> 2.5)
            has_gm = np.any(seg2d == 2)
            has_wm = np.any(seg2d == 3)
            if has_gm and has_wm:
                ax.contour(
                    seg2d.astype(float),
                    levels=[2.5],
                    colors=contour_color_gmwm,
                    linewidths=gmwm_lw,
                    zorder=5,
                )

            ax.text(
                0.02, 0.98, label_text,
                transform=ax.transAxes,
                ha="left", va="top",
                color="yellow",
                fontsize=label_pt,
                bbox=dict(facecolor="black", alpha=0.35, edgecolor="none", pad=1),
                zorder=10,
            )

            if draw_lr:
                ax.text(
                    0.02, 0.02, "L",
                    transform=ax.transAxes,
                    ha="left", va="bottom",
                    color="cyan",
                    fontsize=lr_pt,
                    fontweight="bold",
                    bbox=dict(facecolor="black", alpha=0.30, edgecolor="none", pad=1),
                    zorder=10,
                )
                ax.text(
                    0.98, 0.02, "R",
                    transform=ax.transAxes,
                    ha="right", va="bottom",
                    color="cyan",
                    fontsize=lr_pt,
                    fontweight="bold",
                    bbox=dict(facecolor="black", alpha=0.30, edgecolor="none", pad=1),
                    zorder=10,
                )

            ax.set_axis_off()
            fig.canvas.draw()

            # Get RGB (compatible across matplotlib versions)
            if hasattr(fig.canvas, "buffer_rgba"):
                rgba = np.asarray(fig.canvas.buffer_rgba())
                rgb = rgba[..., :3].copy()
            else:
                buf = np.frombuffer(fig.canvas.tostring_argb(), dtype=np.uint8)
                wpx, hpx = fig.canvas.get_width_height()
                argb = buf.reshape((hpx, wpx, 4))
                rgba = argb[..., [1, 2, 3, 0]]
                rgb = rgba[..., :3].copy()

            plt.close(fig)

            # Size alignment: only allow cropping to (H,W), no padding
            h2, w2 = rgb.shape[:2]
            if (h2, w2) != (H, W):
                if h2 < H or w2 < W:
                    raise RuntimeError(f"Rendered size smaller than target and padding is forbidden: got {(h2,w2)}, need {(H,W)}")
                y0 = (h2 - H) // 2
                x0 = (w2 - W) // 2
                rgb = rgb[y0:y0+H, x0:x0+W, :]

            return rgb


        def generate_fmri_coreg_t1w_qc_montage_3x3(
            mean_fmri_registered_to_t1w: str,
            t1w_brain_mask: str,
            t1w_brain_seg: str,
            out_dir: str,
            save_name: str = None,
            num_slices_per_view: int = 3,
            tile_width: int = 240,              # unified width (for upscaling, avoiding "tiny brain")
            fmri_vmin_pct: float = 2,
            fmri_vmax_pct: float = 98,
            brainmask_linewidth: float = 1.5,
            gmwm_linewidth: float = 1.2,
            contour_color_mask: str = "red",
            contour_color_gmwm: str = "red",    # change to "blue" for clearer distinction
        ):
            """
            fMRI->T1w coreg QC:
            - Background: mean fMRI (already in T1w space)
            - Contour: T1w brain mask + GM/WM boundary
            - 3x3 montage (axial/sagittal/coronal x 3 slices)
            - Seamless concatenation (np.concatenate)
            - axial/coronal: L/R annotations with automatic L-on-left, R-on-right
            """
            os.makedirs(out_dir, exist_ok=True)

            fmri_nii = nib.load(mean_fmri_registered_to_t1w)
            mask_nii = nib.load(t1w_brain_mask)
            seg_nii = nib.load(t1w_brain_seg)

            fmri = fmri_nii.get_fdata()
            mask = (mask_nii.get_fdata() > 0.5)
            seg = seg_nii.get_fdata()

            if fmri.shape != mask.shape or fmri.shape != seg.shape:
                # from nibabel.processing import resample_from_to
                # # Use mask_nii's (shape, affine) as the target
                # fmri_nii_rs = resample_from_to(
                #     fmri_nii,
                #     (mask_nii.shape, mask_nii.affine),
                #     order=1  # continuous intensity image: linear interpolation
                # )
                # fmri = fmri_nii_rs.get_fdata()

                raise ValueError(f"shape mismatch: fmri {fmri.shape}, mask {mask.shape}, seg {seg.shape}")

            # mean fMRI intensity window (using non-zero is more stable)
            fmri_nz = fmri[fmri != 0]
            if fmri_nz.size > 0:
                vmin = float(np.percentile(fmri_nz, fmri_vmin_pct))
                vmax = float(np.percentile(fmri_nz, fmri_vmax_pct))
                if vmax <= vmin:
                    vmin, vmax = float(np.min(fmri_nz)), float(np.max(fmri_nz))
            else:
                vmin, vmax = float(np.min(fmri)), float(np.max(fmri))

            # Use fMRI affine to determine whether flipping is needed (fmri is already in T1w space; mask/seg are in the same space)
            flip_lr = _need_flip_lr(fmri_nii.affine)

            views = ["axial", "sagittal", "coronal"]
            row_imgs = []

            # Slice selection: use T1w brain mask to determine bbox-cuts range (more reasonable)
            for view in views:
                idxs = _get_mask_indices(mask, view=view, num_slices=num_slices_per_view)
                tiles = []

                for idx, axis_name in idxs:
                    if view == "axial":
                        fmri_sl = fmri[:, :, idx]
                        mask_sl = mask[:, :, idx]
                        seg_sl = seg[:, :, idx]
                    elif view == "sagittal":
                        fmri_sl = fmri[idx, :, :]
                        mask_sl = mask[idx, :, :]
                        seg_sl = seg[idx, :, :]
                    else:  # coronal
                        fmri_sl = fmri[:, idx, :]
                        mask_sl = mask[:, idx, :]
                        seg_sl = seg[:, idx, :]

                    # Unify display space: transpose
                    fmri2d = fmri_sl.T
                    mask2d = mask_sl.T.astype(np.uint8)
                    seg2d = seg_sl.T

                    # axial/coronal: ensure L on the left and R on the right (flip if needed)
                    if view in ("axial", "coronal") and flip_lr:
                        fmri2d = np.fliplr(fmri2d)
                        mask2d = np.fliplr(mask2d)
                        seg2d = np.fliplr(seg2d)

                    # Unify all tile widths (the previous "seamless concatenation logic")
                    W = int(tile_width)
                    fmri2d = _scale_to_width_nn(fmri2d, W)
                    mask2d = _scale_to_width_nn(mask2d, W)
                    seg2d = _scale_to_width_nn(seg2d, W)

                    label = f"{axis_name}={int(idx)}"
                    draw_lr = (view in ("axial", "coronal"))

                    rgb = _render_fmri_coreg_tile_rgb_exact(
                        fmri2d=fmri2d,
                        brainmask2d=mask2d,
                        seg2d=seg2d,
                        label_text=label,
                        draw_lr=draw_lr,
                        vmin=vmin,
                        vmax=vmax,
                        brainmask_lw=brainmask_linewidth,
                        gmwm_lw=gmwm_linewidth,
                        contour_color_mask=contour_color_mask,
                        contour_color_gmwm=contour_color_gmwm,
                    )
                    tiles.append(rgb)

                # Heights within a row should be consistent (same view, same shape, same scaling)
                hs = [t.shape[0] for t in tiles]
                if len(set(hs)) != 1:
                    raise RuntimeError(f"{view} row tile heights inconsistent: {hs} (should not happen; check whether inputs are in the same space and resolution).")

                row = np.concatenate(tiles, axis=1)  # horizontal seamless
                row_imgs.append(row)

            # All three row widths should match (= 3*tile_width)
            ws = [r.shape[1] for r in row_imgs]
            if len(set(ws)) != 1:
                raise RuntimeError(f"Row widths inconsistent: {ws} (should not happen).")

            montage = np.concatenate(row_imgs, axis=0)  # vertical seamless

            out_path = os.path.join(out_dir, save_name + "_QC_fMRI_CoregTo_T1w.png")
            plt.imsave(out_path, montage)
            return out_path


