def smri_skull_stripping_qc(
    original_t1w_path: str,
    brain_mask_path: str,
    metric_or_visual: str,
    # visual_qc_choice: str,
    # tool_call_id: Annotated[str, InjectedToolCallId],
):
    """
    Perform quality control on the skull stripping step of structural MRI for a subject. 

    **Parameters:**
    - original_t1w_path: (str). Absolute path to the original, raw T1-weighted MRI image of a subject.
    - brain_mask_path: (str). Absolute path to the brain mask of a subject.
    - metric_or_visual: (str). Choice of metric or visual QC. 'metric' or 'visual'.

    **Outputs:**
    - If metric_or_visual is 'metric', return the brain volume size in ml as a python dictionary with one key: {'brain_volume_size': <volume_in_ml>}
    - If metric_or_visual is 'visual', return the visual evaluation result of the skull stripping step.


    """

    import os
    import numpy as np
    import nibabel as nib
    from nibabel.processing import resample_from_to
    import matplotlib.pyplot as plt
    from matplotlib.gridspec import GridSpec

    def construct_skull_stripping_qc_image(
        original_t1w_path: str,
        brain_mask_path: str
    ):

        def _get_slices(data, mask, view='axial', num_slices=16):
            view = view.lower()
            if view not in ['axial', 'sagittal', 'coronal']:
                raise ValueError("view must be 'axial', 'sagittal' or 'coronal'")

            if data.shape != mask.shape:
                raise ValueError(f"data.shape={data.shape} and mask.shape={mask.shape} are not consistent")

            mask_bool = mask.astype(bool)

            if view == 'axial':
                axis = 2
                axis_name = 'Z'
                frac = 0.30
            elif view == 'sagittal':
                axis = 0
                axis_name = 'X'
                frac = 0.20
            else:  # coronal
                axis = 1
                axis_name = 'Y'
                frac = 0.10

            shape = mask_bool.shape
            slice_area = int(np.prod([shape[i] for i in range(3) if i != axis]))  # pixels per slice
            if slice_area <= 0:
                raise ValueError("slice_area<=0")

            sum_axes = tuple(i for i in range(3) if i != axis)
            c = mask_bool.sum(axis=sum_axes) 

            th = int(np.ceil(slice_area * frac))

            B = np.where(c > th)[0]
            if B.size < num_slices:
                B = np.where(c > 0)[0]

            if B.size == 0:
                raise ValueError("ALl zero voxels in the mask")

            smin = int(B.min())
            smax = int(B.max())
            if smax <= smin:
                chosen = np.array([smin], dtype=int)
            else:
                cut_coords = np.linspace(smin, smax, num_slices + 2, dtype=float)[1:-1]
                chosen = np.unique(np.clip(np.rint(cut_coords).astype(int), smin, smax))

                if chosen.size < min(num_slices, (smax - smin + 1)):
                    full = np.arange(smin, smax + 1, dtype=int)
                    if full.size <= num_slices:
                        chosen = full
                    else:
                        pos = np.linspace(0, full.size - 1, num_slices, dtype=int)
                        chosen = np.unique(full[pos])

            slices = []
            for idx in chosen.tolist():
                if view == 'axial':
                    img_slice = data[:, :, idx]
                    mask_slice = mask_bool[:, :, idx]
                elif view == 'sagittal':
                    img_slice = data[idx, :, :]
                    mask_slice = mask_bool[idx, :, :]
                else:  # coronal
                    img_slice = data[:, idx, :]
                    mask_slice = mask_bool[:, idx, :]

                slices.append((img_slice, mask_slice, int(idx), axis_name))

            return slices


        def _need_flip_lr(affine):
            xcode = nib.aff2axcodes(affine)[0]  
            return (xcode == 'L')


        def _scale_to_width_nn(arr2d, target_w):
            h, w = arr2d.shape
            if w == target_w:
                return arr2d
            scale = target_w / float(w)
            target_h = max(1, int(np.rint(h * scale)))

            ys = np.linspace(0, h - 1, target_h)
            xs = np.linspace(0, w - 1, target_w)
            yi = np.clip(np.rint(ys).astype(int), 0, h - 1)
            xi = np.clip(np.rint(xs).astype(int), 0, w - 1)
            return arr2d[yi[:, None], xi[None, :]]


        def _render_tile_rgb_exact(img2d, msk2d, label_text, draw_lr, vmin, vmax, lw=1.0):
            H, W = img2d.shape

            dpi = 100
            fig = plt.figure(figsize=(W / dpi, H / dpi), dpi=dpi)
            ax = plt.axes([0, 0, 1, 1])

            ax.imshow(
                img2d, cmap="gray", origin="lower",
                vmin=vmin, vmax=vmax,
                aspect="equal",
                interpolation="nearest",
            )
            ax.contour(msk2d.astype(float), levels=[0.5], colors="red", linewidths=lw)

            ax.text(
                0.02, 0.98, label_text,
                transform=ax.transAxes, ha="left", va="top",
                color="yellow", fontsize=10,
                bbox=dict(facecolor="black", alpha=0.4, edgecolor="none", pad=1),
            )

            if draw_lr:
                ax.text(
                    0.02, 0.02, "L",
                    transform=ax.transAxes, ha="left", va="bottom",
                    color="cyan", fontsize=10, fontweight="bold",
                    bbox=dict(facecolor="black", alpha=0.35, edgecolor="none", pad=1),
                )
                ax.text(
                    0.98, 0.02, "R",
                    transform=ax.transAxes, ha="right", va="bottom",
                    color="cyan", fontsize=10, fontweight="bold",
                    bbox=dict(facecolor="black", alpha=0.35, edgecolor="none", pad=1),
                )

            ax.set_axis_off()
            fig.canvas.draw()

            # --- Get RGB (compatible across matplotlib versions) ---
            if hasattr(fig.canvas, "buffer_rgba"):
                rgba = np.asarray(fig.canvas.buffer_rgba())
                rgb = rgba[..., :3].copy()
            else:
                buf = np.frombuffer(fig.canvas.tostring_argb(), dtype=np.uint8)
                wpx, hpx = fig.canvas.get_width_height()
                argb = buf.reshape((hpx, wpx, 4))
                rgba = argb[..., [1, 2, 3, 0]]
                rgb = rgba[..., :3].copy()

            plt.close(fig)

            # --- If there is a 1-2 pixel difference, only center-crop to (H, W); no padding ---
            h2, w2 = rgb.shape[:2]
            if (h2, w2) != (H, W):
                if h2 < H or w2 < W:
                    raise RuntimeError(
                        f"matplotlib rendered size smaller than target and padding is forbidden: got {(h2, w2)}, need {(H, W)}"
                    )
                y0 = (h2 - H) // 2
                x0 = (w2 - W) // 2
                rgb = rgb[y0:y0 + H, x0:x0 + W, :]

            return rgb


        def generate_qc_montage_3x3(
            t1_path,
            mask_path,
            out_dir,
            vmax_percentile=99,
            contour_linewidth=1.0,
            save_name=None
        ):
            """
            Generate a 3x3 montage strictly per the rules:
            - Use the axial width as X
            - All tiles are proportionally scaled to width X (no padding, no background fill)
            - The 3 tiles per row (same view) share the same height -> horizontal concatenation directly
            - The 3 rows are concatenated vertically directly
            """
            os.makedirs(out_dir, exist_ok=True)

            # load
            t1_nii = nib.load(t1_path)
            mask_nii = nib.load(mask_path)
            t1 = t1_nii.get_fdata()
            mask = (mask_nii.get_fdata() > 0.5)

            vmin = float(np.min(t1))
            vmax = float(np.percentile(t1, vmax_percentile))

            flip_lr = _need_flip_lr(t1_nii.affine)

            views = ["axial", "sagittal", "coronal"]
            per_view = 3

            # First take axial to define X (display space: we use .T)
            axial_slices = _get_slices(t1, mask, view="axial", num_slices=per_view)
            while len(axial_slices) < per_view:
                axial_slices.append(axial_slices[-1])

            X = axial_slices[0][0].T.shape[1]  # unified width

            row_imgs = []
            for v in views:
                slices = axial_slices if v == "axial" else _get_slices(t1, mask, view=v, num_slices=per_view)
                while len(slices) < per_view:
                    slices.append(slices[-1])

                tiles = []
                for (img_slice, mask_slice, idx, axis_name) in slices[:per_view]:
                    img2d = img_slice.T
                    msk2d = mask_slice.T.astype(np.uint8)

                    # L/R: flip axial & coronal if needed
                    if v in ("axial", "coronal") and flip_lr:
                        img2d = np.fliplr(img2d)
                        msk2d = np.fliplr(msk2d)

                    # Proportional scaling to width X (no padding)
                    img2d = _scale_to_width_nn(img2d, X)
                    msk2d = _scale_to_width_nn(msk2d, X)

                    label = f"{axis_name}={int(idx)}"
                    draw_lr = (v in ("axial", "coronal"))

                    rgb = _render_tile_rgb_exact(
                        img2d, msk2d, label, draw_lr,
                        vmin=vmin, vmax=vmax,
                        lw=contour_linewidth
                    )
                    tiles.append(rgb)

                # The 3 tiles in this row should have the same height; if not, prior processing/shape assumptions are violated
                hs = [t.shape[0] for t in tiles]
                if len(set(hs)) != 1:
                    raise RuntimeError(f"{v} row tile heights inconsistent: {hs}. This should generally not happen.")

                row = np.concatenate(tiles, axis=1)  # horizontal concatenation (no background)
                row_imgs.append(row)

            # All three rows should have width 3*X; heights may differ but won't affect vertical concatenation (only widths must match)
            ws = [r.shape[1] for r in row_imgs]
            if len(set(ws)) != 1:
                raise RuntimeError(f"Row widths inconsistent: {ws}. This should not happen (all tile widths should be X).")

            montage = np.concatenate(row_imgs, axis=0)  # vertical concatenation (no background)

            out_path = os.path.join(out_dir, save_name + "_QC_T1w_SkullStrip.png")
            plt.imsave(out_path, montage)
            return out_path


        # construct visual element
        # output directory should be same as the mask_path
        out = os.path.dirname(brain_mask_path)
        save_name = get_nii_basename(brain_mask_path)

        png_path = generate_qc_montage_3x3(
            t1_path=original_t1w_path,
            mask_path=brain_mask_path,
            out_dir=out,
            contour_linewidth=1.5,
            save_name=save_name
        )

        return png_path


    from typing import Dict
