def run_mriqc(bids_dir: str, output_dir: str, modality: Optional[list[str]]) -> str:
# def run_mriqc(bids_dir: str, output_dir: str, temp_work_dir: str, modality: Optional[list[str]] = None, participant_label: Optional[list[str]] = None) -> str:
    """
    Call MRIQC tool to calculate image quality metrics (IQMs) on all subjects and generate corresponding quality reports for quality control before any preprocessing.

    **Parameters:**
    - bids_dir (str): Absolute path to the BIDS input dataset.
    - output_dir (str): Absolute path to the output directory. 
    - modality (list[str]): Specific modality to measure, valid options are 'T1w' and 'bold'.

    **Outputs:**
    - Artifacts generated by MRIQC under `output_dir`:
	  - For each processed subject `sub-<label>`:
	    - Image quality metrics (IQMs) JSON files, e.g.:
	      - `sub-<label>/ses-<label>/anat/sub-<label>_T1w.json`
	      - `sub-<label>/ses-<label>/func/sub-<label>_*_bold.json` (if BOLD exists)
	    - Per-image HTML report, e.g.:
	      - `sub-<label>_ses-<label>_T1w.html`
	      - `sub-<label>_ses-<label>_bold.html`

    This python tool itself has no return value, only generates MRIQC derivatives in the corresponding output_dir.
    
    """

    # #######
    # return "MRIQC has been run successfully."
    # #######

    # check modality validity
    for i, m in enumerate(modality):
        ml = m.lower()
        if ml not in ['t1w', 'bold']:
            return f"Error: Unsupported modality: {m}, supported modalities are 'T1w' and 'bold'."
        modality[i] = 'T1w' if ml == 't1w' else 'bold'

    
    if modality and len(modality) > 0:
        modality_str = " ".join(modality)
    else:
        modality_str = "T1w bold"

    temp_work_dir = os.path.join(output_dir, "work")
    temp_bidsdb_dir = os.path.join(output_dir, "bidsdb")

    num_subjects = len(glob.glob(os.path.join(bids_dir, 'sub-*')))
    number_jobs_needed = num_subjects // 2

    os.makedirs(output_dir, exist_ok=True)
    os.makedirs(temp_work_dir, exist_ok=True)
    os.makedirs(temp_bidsdb_dir, exist_ok=True)
 
    subjects_list = []
    for sub_path in glob.glob(os.path.join(bids_dir, 'sub-*')):
        sub = sub_path.split('/')[-1].replace('sub-', '')
        subjects_list.append(sub)
    subjects_list = [subjects_list[i:i+2] for i in range(0, len(subjects_list), 2)]

    temp_dir = 'Path/temp_workspace/temp'
    os.makedirs(temp_dir, exist_ok=True)

    mriqc_subjects_txt_path = os.path.join(temp_dir, 'MRIQC_subjects.txt')
    with open(mriqc_subjects_txt_path, 'w') as f:
        for subjects in subjects_list:
            f.write(' '.join(subjects) + '\n')

    slurm_outputs_dir = 'Path/temp_workspace/slurm_outputs'
    os.makedirs(slurm_outputs_dir, exist_ok=True)

    slurm_script = f"""#!/bin/bash
#SBATCH --job-name=parallel_mriqc
#SBATCH --array=1-{number_jobs_needed}%20
#SBATCH --cpus-per-task=4
#SBATCH --mem=32G
#SBATCH --gres=gpu:0
#SBATCH --output=Path/temp_workspace/slurm_outputs/parallel_mriqc-%A_%a.out

set -euo pipefail

SUBJECT_LIST={mriqc_subjects_txt_path}

base_dir_work={temp_work_dir}
base_dir_bidsdb_dir={temp_bidsdb_dir}

line="$(sed -n "${{SLURM_ARRAY_TASK_ID}}p" "${{SUBJECT_LIST}}")"

read -r sub1 sub2 <<< "${{line}}"

temp_work_dir="${{base_dir_work}}/job_${{SLURM_JOB_ID}}_task_${{SLURM_ARRAY_TASK_ID}}"
temp_bidsdb_dir="${{base_dir_bidsdb_dir}}/job_${{SLURM_JOB_ID}}_task_${{SLURM_ARRAY_TASK_ID}}"

mkdir -p "${{temp_work_dir}}"
mkdir -p "${{temp_bidsdb_dir}}"

# Command to run the python script
python Path/source/tool_lib/parallel_mriqc.py \
  --bids-dir {bids_dir} \
  --output-dir {output_dir} \
  --temp-work-dir "${{temp_work_dir}}" \
  --temp-bidsdb-dir "${{temp_bidsdb_dir}}" \
  --modality {modality_str} \
  --participant-label ${{sub1}} ${{sub2}}
    """
    # write to temp_dir as a slurm script
    with open(os.path.join(temp_dir, 'parallel_mriqc.sh'), 'w') as f:
        f.write(slurm_script)

    run_command(f"sbatch --wait {os.path.join(temp_dir, 'parallel_mriqc.sh')}")
    



