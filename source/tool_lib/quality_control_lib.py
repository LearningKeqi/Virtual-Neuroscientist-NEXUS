def get_mriqc_group_level_tsv_and_outliers(
    modality: str, 
    metric_keys: Optional[list[str]] = None, 
    output_dir: str = None,
    temp_work_dir: str = None):

    """
    Get the group-level TSV (`group_T1w.tsv` / `group_bold.tsv` in `output_dir`) and detected outliers of MRIQC IQMs from group-level MRIQC results.

    **Parameters:**
    - modality (str): 'T1w' or 'bold'.
    - metric_keys (list[str] | None): IQM metrics to evaluate; if None, use all numeric columns.
        - For T1w: valid metric keys include: ['cjv',	'cnr',	'efc',	'fber',	'fwhm_avg',	'fwhm_x',	'fwhm_y',	'fwhm_z',	'icvs_csf',	'icvs_gm',	'icvs_wm',	'inu_med',	'inu_range',	'qi_1',	'qi_2',	'rpve_csf',	'rpve_gm',	'rpve_wm',	'size_x',	'size_y',	'size_z',	'snr_csf',	'snr_gm',	'snr_total',	'snr_wm',	'snrd_csf',	'snrd_gm',	'snrd_total',	'snrd_wm',	'spacing_x',	'spacing_y',	'spacing_z',	'summary_bg_k',	'summary_bg_mad',	'summary_bg_mean',	'summary_bg_median',	'summary_bg_n',	'summary_bg_p05',	'summary_bg_p95',	'summary_bg_stdv',	'summary_csf_k',	'summary_csf_mad',	'summary_csf_mean',	'summary_csf_median',	'summary_csf_n',	'summary_csf_p05',	'summary_csf_p95',	'summary_csf_stdv',	'summary_gm_k',	'summary_gm_mad',	'summary_gm_mean',	'summary_gm_median',	'summary_gm_n',	'summary_gm_p05',	'summary_gm_p95',	'summary_gm_stdv',	'summary_wm_k',	'summary_wm_mad',	'summary_wm_mean',	'summary_wm_median',	'summary_wm_n',	'summary_wm_p05',	'summary_wm_p95',	'summary_wm_stdv',	'tpm_overlap_csf',	'tpm_overlap_gm',	'tpm_overlap_wm',	'wm2max'].
        - For bold: valid metric keys include: ['aor',	'aqi',	'dummy_trs',	'dvars_nstd',	'dvars_std',	'dvars_vstd',	'efc',	'fber',	'fd_mean',	'fd_num',	'fd_perc',	'fwhm_avg',	'fwhm_x',	'fwhm_y',	'fwhm_z',	'gcor',	'gsr_x',	'gsr_y',	'size_t',	'size_x',	'size_y',	'size_z',	'snr',	'spacing_tr',	'spacing_x',	'spacing_y',	'spacing_z',	'summary_bg_k',	'summary_bg_mad',	'summary_bg_mean',	'summary_bg_median',	'summary_bg_n',	'summary_bg_p05',	'summary_bg_p95',	'summary_bg_stdv',	'summary_fg_k',	'summary_fg_mad',	'summary_fg_mean',	'summary_fg_median',	'summary_fg_n',	'summary_fg_p05',	'summary_fg_p95',	'summary_fg_stdv',	'tsnr'].
    - output_dir (str): MRIQC output root directory containing the group-level TSV, same as the output_dir of `run_mriqc` tool.
    - temp_work_dir (str): Absolute path to the temporary work directory.

    **Outputs:**
    - group-level TSV: `group_T1w.tsv` / `group_bold.tsv` in `output_dir`
    - dict: A python dictionary with the following keys when successful:
        - modality (str): Either 'T1w' or 'bold' (normalized from input).
        - metrics (list[str]): The numeric IQM metric names that were evaluated.
        - stats (dict[str, dict]): Per-metric summary statistics and IQR bounds.
            For each metric, includes:
                - count (int): Number of non-NaN samples used.
                - q1 (float): 25th percentile.
                - q3 (float): 75th percentile.
                - iqr (float): Interquartile range (q3 - q1).
                - lower_bound (float): Outlier lower bound (q1 - 1.5 * iqr).
                - upper_bound (float): Outlier upper bound (q3 + 1.5 * iqr).
        - outliers (list[dict]): A list of detected outlier records. Each record contains:
            - bids_name (str): Scan identifier from the TSV 'bids_name' column.
            - metric (str): Metric name where the outlier was detected.
            - value (float): Metric value (rounded to 4 decimals).
            - direction (str): 'Too low' or 'Too high'.

    """

    # run group-level mriqc command
    group_mriqc_command = (f"apptainer run --cleanenv \
    -B Path/demo_data:/data:ro \
    -B {output_dir}:/out \
    -B {temp_work_dir}:/work \
    Path/tools/mriqc_24.0.2.sif \
    /data /out group \
    --no-sub \
    --work-dir /work \
    --n_procs 12 --mem_gb 32 \
    --verbose-reports"
    )

    print("group_mriqc_command output:")
    print(run_command(group_mriqc_command))
    print("--------------------------------")


    mod = (modality or '').strip().lower()
    if mod not in {'t1w', 'bold'}:
        return f"Error: Unsupported modality: {modality}, supported modalities are 'T1w' and 'bold'."

    tsv_path = os.path.join(output_dir, f"group_{'T1w' if mod=='t1w' else 'bold'}.tsv")
    if not os.path.isfile(tsv_path):
        return f"Error: Group TSV not found: {tsv_path}"

    try:
        df = pd.read_csv(tsv_path, sep='\t')
    except Exception as e:
        return f"Error: Failed to read TSV: {str(e)}"

    if df.empty:
        return f"Error: Group TSV is empty, path: {tsv_path}"

    if 'bids_name' not in df.columns:
        return f"Error: Missing 'bids_name' column in group TSV"

    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    target_metrics = [m for m in (metric_keys or numeric_cols) if m in numeric_cols]

    if not target_metrics:
        return "Error: No valid numeric metrics to evaluate"

    def r4(x: float) -> float:
        try:
            return float(round(float(x), 4))
        except Exception:
            return float('nan')

    stats = {}
    outliers = []

    for metric in target_metrics:
        
        series = df[metric].astype(float)
        q1 = float(np.nanpercentile(series, 25))
        q3 = float(np.nanpercentile(series, 75))
        iqr = q3 - q1

        k = 3
        lower = q1 - k * iqr
        upper = q3 + k * iqr

        stats[metric] = {
            "count": int(series.notna().sum()),
            "q1": r4(q1),
            "q3": r4(q3),
            "iqr": r4(iqr),
            "lower_bound": r4(lower),
            "upper_bound": r4(upper)
        }

        mask_low = series < lower
        mask_high = series > upper

        for idx in df.index[mask_low]:
            outliers.append({
                "bids_name": str(df.at[idx, 'bids_name']),
                "metric": metric,
                "value": r4(df.at[idx, metric]),
                "direction": "Too low"
            })
        for idx in df.index[mask_high]:
            outliers.append({
                "bids_name": str(df.at[idx, 'bids_name']),
                "metric": metric,
                "value": r4(df.at[idx, metric]),
                "direction": "Too high"
            })

    result = {
        "modality": 'T1w' if mod == 't1w' else 'bold',
        "metrics": target_metrics,
        "stats": stats,
        "outliers": outliers
    }

    # return json.dumps(result, ensure_ascii=False)

    return result


